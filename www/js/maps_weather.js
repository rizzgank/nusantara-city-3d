function gaussianPeak(nx, nz, px, pz, radiusX, radiusZ, height) {
  const dx = (nx - px) / radiusX;
  const dz = (nz - pz) / radiusZ;
  return height * Math.exp(-(dx * dx + dz * dz));
}

function ridgeNoise(x, z) {
  const n1 = Math.sin(x * 0.045) * Math.cos(z * 0.045);
  const n2 = Math.sin(x * 0.11 + z * 0.09) * 0.5;
  const n3 = Math.cos(x * 0.23 - z * 0.19) * 0.25;
  return (1 - Math.abs(n1)) * 2.1 + n2 + n3;
}

window.generateRegionHeight = function (region, x, z, halfSize) {
  const nx = x / halfSize;
  const nz = z / halfSize;
  const detail = ridgeNoise(x, z);

  if (region.terrainType === "malang_real") {
    const arjuno = gaussianPeak(nx, nz, -0.14, -0.78, 0.34, 0.28, 34.0);
    const welirang = gaussianPeak(nx, nz, -0.38, -0.82, 0.24, 0.22, 27.0);
    const batuHills = gaussianPeak(nx, nz, -0.62, -0.45, 0.3, 0.34, 15.5);
    const kawi = gaussianPeak(nx, nz, -0.84, 0.05, 0.26, 0.42, 26.0);
    const bromo = gaussianPeak(nx, nz, 0.86, -0.25, 0.24, 0.36, 25.0);
    const semeru = gaussianPeak(nx, nz, 0.86, 0.48, 0.3, 0.34, 38.0);
    const southHills = Math.max(0, nz - 0.74) * 18.0;

    let h = 1.75 + arjuno + welirang + batuHills + kawi + bromo + semeru + southHills;
    const mountainFactor = Math.min(1, (h - 2.0) / 14.0);
    h += detail * (0.18 + mountainFactor * 2.1);

    // Sungai Brantas di sisi Barat-Tengah (jauh dari Tol Pandaan-Malang di x = +58)
    const brantasX = -18 + Math.sin(z * 0.032) * 15 + Math.cos(z * 0.07) * 4;
    const distBrantas = Math.abs(x - brantasX);
    if (distBrantas < 7.2 && nz > -0.55) {
      const t = 1 - distBrantas / 7.2;
      h -= t * t * 4.4;
    }
    return h;
  }

  if (region.terrainType === "bandung_real") {
    const tangkuban = gaussianPeak(nx, nz, -0.05, -0.78, 0.45, 0.26, 30.0);
    const manglayang = gaussianPeak(nx, nz, 0.58, -0.68, 0.35, 0.28, 22.0);
    const ciwidey = gaussianPeak(nx, nz, -0.45, 0.78, 0.48, 0.28, 26.0);
    const pangalengan = gaussianPeak(nx, nz, 0.45, 0.8, 0.48, 0.28, 25.0);
    const eastRim = Math.max(0, nx - 0.74) * 20.0;

    let h = 1.75 + tangkuban + manglayang + ciwidey + pangalengan + eastRim;
    const mFactor = Math.min(1, (h - 2.0) / 12.0);
    h += detail * (0.18 + mFactor * 1.9);

    // Sungai Citarum di bagian Selatan lembah (z ~ +32, jauh dari Tol Padaleunyi di z ~ -46)
    const citarumZ = 32 + Math.sin(x * 0.035) * 12;
    const distRiver = Math.abs(z - citarumZ);
    if (distRiver < 7.0) {
      const t = 1 - distRiver / 7.0;
      h -= t * t * 4.3;
    }
    return h;
  }

  if (region.terrainType === "jakarta_real") {
    if (nz < -0.54) {
      const island1 = gaussianPeak(nx, nz, -0.35, -0.78, 0.09, 0.08, 4.6);
      const island2 = gaussianPeak(nx, nz, 0.25, -0.84, 0.07, 0.07, 4.2);
      return -2.2 - (-0.54 - nz) * 12.0 + island1 + island2 + detail * 0.2;
    }
    const bogorHills = Math.max(0, nz - 0.76) * 22.0;
    let h = 1.65 + bogorHills + detail * 0.22;

    // Sungai Ciliwung di tengah-barat (jauh dari Tol Jagorawi di x = +58)
    const ciliwungX = -4 + Math.sin(z * 0.038) * 12;
    const distRiver = Math.abs(x - ciliwungX);
    if (distRiver < 6.8) {
      const t = 1 - distRiver / 6.8;
      h -= t * t * 4.1;
    }
    return h;
  }

  if (region.terrainType === "surabaya_real") {
    if (nz < -0.58 || nx > 0.62) {
      const seaN = Math.max(0, -0.58 - nz);
      const seaE = Math.max(0, nx - 0.62);
      return -2.0 - (seaN + seaE) * 14.0 + detail * 0.18;
    }
    const southHills = gaussianPeak(nx, nz, 0.25, 0.88, 0.45, 0.22, 11.0);
    let h = 1.65 + southHills + detail * 0.2;

    // Sungai Kalimas di tengah-timur (jauh dari Tol Waru-Gempol di x = -62)
    const kalimasX = 8 + Math.sin(z * 0.035) * 11;
    const distRiver = Math.abs(x - kalimasX);
    if (distRiver < 6.5) {
      const t = 1 - distRiver / 6.5;
      h -= t * t * 4.0;
    }
    return h;
  }

  if (region.terrainType === "yogya_real") {
    if (nz > 0.74) {
      return -2.2 - (nz - 0.74) * 16.0 + detail * 0.15;
    }
    const merapi = gaussianPeak(nx, nz, 0.02, -0.74, 0.36, 0.28, 36.0);
    const merbabu = gaussianPeak(nx, nz, -0.34, -0.84, 0.25, 0.22, 24.0);
    const menoreh = gaussianPeak(nx, nz, -0.82, -0.15, 0.25, 0.45, 15.0);

    let h = 1.7 + merapi + merbabu + menoreh;
    const mFactor = Math.min(1, (h - 2.0) / 14.0);
    h += detail * (0.18 + mFactor * 1.8);

    // Kali Code di barat-tengah (jauh dari Tol Jogja-Solo di x > +66)
    const codeX = -14 + Math.sin(z * 0.04) * 9;
    const distRiver = Math.abs(x - codeX);
    if (distRiver < 5.5 && nz > -0.45) {
      const t = 1 - distRiver / 5.5;
      h -= t * t * 3.8;
    }
    return h;
  }

  if (region.terrainType === "ikn_real") {
    const bayDist = Math.hypot((nx - 0.75) * 1.1, (nz - 0.75) * 1.1);
    if (bayDist < 0.58) {
      return -2.2 - (0.58 - bayDist) * 14.0;
    }
    const hills =
      gaussianPeak(nx, nz, -0.65, -0.55, 0.36, 0.4, 13.0) +
      gaussianPeak(nx, nz, 0.55, -0.48, 0.36, 0.35, 11.5) +
      gaussianPeak(nx, nz, -0.62, 0.42, 0.35, 0.38, 12.0);
    let h = 1.85 + hills + detail * 0.75;

    // Sungai Sepaku di tengah-selatan (z ~ +24, jauh dari Tol Utara di z < -70)
    const riverZ = 24 + Math.sin(x * 0.03) * 14;
    const distRiver = Math.abs(z - riverZ);
    if (distRiver < 7.0) {
      const t = 1 - distRiver / 7.0;
      h -= t * t * 4.4;
    }
    return h;
  }

  if (region.terrainType === "bali_real") {
    const agung = gaussianPeak(nx, nz, 0.25, -0.76, 0.36, 0.26, 31.0);
    const batukaru = gaussianPeak(nx, nz, -0.45, -0.72, 0.35, 0.25, 22.0);
    const uluwatu = gaussianPeak(nx, nz, -0.1, 0.88, 0.26, 0.14, 9.5);

    const westBay = Math.hypot((nx + 0.75) * 1.1, (nz - 0.55) * 0.95);
    const eastBay = Math.hypot((nx - 0.78) * 1.1, (nz - 0.45) * 0.95);
    if (westBay < 0.52 || eastBay < 0.52) {
      const d = Math.min(westBay, eastBay);
      return -2.0 - (0.52 - d) * 14.0;
    }

    let h = 1.75 + agung + batukaru + uluwatu;
    const mFactor = Math.min(1, (h - 2.0) / 12.0);
    h += detail * (0.2 + mFactor * 1.7);
    return h;
  }

  // makassar_real
  if (nx < -0.54) {
    const pulauSamalona = gaussianPeak(nx, nz, -0.78, -0.25, 0.08, 0.08, 4.4);
    return -2.1 - (-0.54 - nx) * 14.0 + pulauSamalona + detail * 0.18;
  }
  const marosKarst =
    gaussianPeak(nx, nz, 0.75, -0.45, 0.32, 0.42, 23.0) +
    gaussianPeak(nx, nz, 0.78, 0.38, 0.34, 0.42, 25.0);
  let h = 1.7 + marosKarst + detail * 0.55;

  // Sungai Jeneberang di Selatan (z ~ +34, jauh dari Tol Reformasi di Utara z < -70)
  const jeneberangZ = 34 + Math.sin(x * 0.035) * 10;
  const distRiver = Math.abs(z - jeneberangZ);
  if (distRiver < 6.5) {
    const t = 1 - distRiver / 6.5;
    h -= t * t * 4.0;
  }
  return h;
};
